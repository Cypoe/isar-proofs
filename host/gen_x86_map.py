def reg_tables() -> str:
    out = [";; ---------- register tables ----------",
           ";; regc: name -> (code&7, code>>3); all width families share",
           ";; the code space (rax/eax/al -> 0).",
           "regc : <r> <-> <PAIR(lo, hi)> where {"]
    seen = set()
    for d in (isa.REG64, isa.REG32, isa.REG8):
        for name, c in sorted(d.items(), key=lambda kv: (kv[1], kv[0])):
            if name in seen:
                continue
            seen.add(name)
            out.append(f"  | r = '{name} {{ lo = ATOM(4,{c & 7})   "
                       f"hi = ATOM(4,{c >> 3}) }}")
    out.append("}\n")
    out.append(";; rfx: regfield contribution ((code&7)<<3)")
    out.append("rfx : <r> <-> <v> where {")
    seen.clear()
    for d in (isa.REG64, isa.REG32, isa.REG8):
        for name, c in sorted(d.items(), key=lambda kv: (kv[1], kv[0])):
            if name in seen:
                continue
            seen.add(name)
            out.append(f"  | r = '{name} {{ v = {(c & 7) << 3} }}")
    out.append("}\n")
    # rex-need: byte regs with code>=4 force REX even when bits are 0
    needing = {n for n, c in isa.REG8.items() if c >= 4}
    out.append(";; rnx1: operand needs a REX byte even when v==0x40")
    out.append("rnx1 : <o> <-> <f> where {")
    for n in sorted(needing):
        out.append(f"  | o = '{n} {{ f = 1 }}")
    for d in (isa.REG64, isa.REG32, isa.REG8):
        for name in sorted(d):
            if name not in needing:
                out.append(f"  | o = '{name} {{ f = 0 }}")
    out.append("  | o = PAIR(_, _) { f = 0 }")
    out.append("}\n")
    out.append("""rnx : <ops> <-> <f> shape self where {
  | ops = [] { f = 0 }
  | fresh(h, t, fh, ft) {
      ops = PAIR(h, t)   rnx1<h> = fh   rnx<t> = ft   or2<fh, ft> = f
    }
}

;; operand -> code lo3 / hi1 (mem base for 'm, 0 for 'p/'l)
plo8 : <o> <-> <lo8> where {
  | fresh(b, lo) {
      regc<o> = PAIR(lo, _)   c48<lo> = lo8
    }
  | fresh(b, d, lo) {
      o = 'm(b, d)   regc<b> = PAIR(lo, _)   c48<lo> = lo8
    }
}
phi : <o> <-> <hi> where {
  | fresh(d) { regc<o> = PAIR(d, hi) }
  | fresh(b, d) { o = 'm(b, d)   regc<b> = PAIR(_, hi) }
  | fresh(n) { o = 'p(n)   hi = ATOM(4,0) }
  | fresh(n) { o = 'l(n)   hi = ATOM(4,0) }
}

;; c48: nibble atom -> same value as a byte atom
c48 : <n: T[4]> <-> <b> where {
%%C48%%
}""")
    return "\n".join(out)


