def nl(v: int, n: int = 8) -> str:
    """LE nibble-list literal."""
    return "[" + ", ".join(f"ATOM(4,{(v >> (4 * i)) & 0xF})"
                           for i in range(n)) + "]"


def bs4(v: int) -> str:
    """LE 4-byte T[8] literal."""
    return "[" + ", ".join(f"ATOM(8,{(v >> (8 * i)) & 0xFF})"
                           for i in range(4)) + "]"


def bl(bs) -> str:
    return "[" + ", ".join(f"ATOM(8,{b})" for b in bs) + "]"


def opbytes(op: int):
    if op > 0xFFFF:
        return [(op >> 16) & 0xFF, (op >> 8) & 0xFF, op & 0xFF]
    if op > 0xFF:
        return [(op >> 8) & 0xFF, op & 0xFF]
    return [op]


class Gen:
    def __init__(self):
        self.n = 0

    def v(self):
        self.n += 1
        return f"v{self.n}"


