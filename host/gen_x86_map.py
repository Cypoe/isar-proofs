def symtab_rel() -> str:
    out = [";; ---------- declared layout (target_pe64.symbols) ----------",
           "symtab : <name> <-> <b4> where {"]
    for name, v in sorted(SYMS.items()):
        out.append(f"  | name = '{name} {{ b4 = {bs4(v)} }}")
    out.append("}")
    return "\n".join(out)


