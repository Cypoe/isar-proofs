def rex_rels() -> str:
    """One rel per distinct rex role-tuple: rex_<roles><vb, ops...>.
    vb is the row-constant base byte 0x40|w<<3 â€” the 'w' role reads the
    row's W flag, so callers inject it (w=0 rows must emit 0x4x)."""
    sigs = {}
    for form, alts in isa.ENCS.items():
        for conds, tmpl in alts:
            for f in tmpl:
                if f[0] == "rex":
                    sigs.setdefault(tuple(f[1:]), None)
    out = [";; ---------- generated rex rels ----------"]
    for roles in sorted(sigs):
        name = "rex_" + "_".join(roles) if roles else "rex_none"
        idxs = sorted({int(r[1:]) for r in roles if r != "w"})
        args = ", ".join(["vb"] + [f"o{i}" for i in idxs])
        opslist = "[" + ", ".join(f"o{i}" for i in idxs) + "]"
        g = Gen()
        lines = []
        acc = "vb"
        for r in roles:
            if r == "w":
                continue
            o = f"o{r[1:]}"
            h = g.v()
            lines.append(f"      phi<{o}> = {h}")
            nv = g.v()
            if r[0] == "R":
                hv = g.v()
                lines.append(f"      hx4<{h}> = {hv}")
                lines.append(f"      bplus<{acc}, {hv}> = {nv}")
            else:
                lines.append(f"      bplus<{acc}, {h}> = {nv}")
            acc = nv
        fvars = ", ".join(f"v{i}" for i in range(1, g.n + 1))
        head = f"{name} : <{args}> <-> <bs> where {{"
        out.append(head)
        if fvars:
            out.append(f"  | fresh({fvars}) {{")
            out.extend(lines)
            out.append(f"      rex_emit<{acc}, {opslist}> = bs")
            out.append("    }")
        else:
            out.append(f"  | fresh(d) {{ rex_emit<{acc}, "
                       f"{opslist}> = bs }}")
        out.append("}")
        out.append("")
    return "\n".join(out)


def _rex_call(roles, w, g):
    """Emit the rex_<roles> call goal for a field; returns the out var."""
    name = ("rex_" + "_".join(roles)) if roles else "rex_none"
    idxs = sorted({int(r[1:]) for r in roles if r != "w"})
    vb = 64 + 8 * (w if "w" in roles else 0)
    callargs = ", ".join([f"ATOM(8,{vb})"]
                         + [f"o{i}" for i in idxs])
    nv = g.v()
    return f"      {name}<{callargs}> = {nv}", nv


def _operand_arity(form: str) -> int:
    """Max operand index referenced by the form's rows/preds."""
    hi = -1
    import re
    for conds, tmpl in isa.ENCS[form]:
        for c in conds:
            hi = max(hi, c[1])
        for f in tmpl:
            for a in f[1:]:
                if isinstance(a, str):
                    for m in re.findall(r"(?:reg|rm|mem|[RB])(\d+)",
                                        a):
                        hi = max(hi, int(m))
                if f[0] in ("imm", "rel"):
                    hi = max(hi, f[-1])
    return hi + 1


def _pred_goals(conds, negate, g, goals):
    """Emit flag goals for a pred list; negate selects the 0-branch."""
    for c in conds:
        pn, idx = c[0], c[1]
        want = "0" if negate else "1"
        if pn in ("i8", "i32"):
            rel = "se8f" if pn == "i8" else "i32f"
            nlv = g.v()
            goals.append(f"      o{idx} = 'i({nlv})")
            goals.append(f"      {rel}<{nlv}> = {want}")
        elif pn == "acc":
            goals.append(f"      accf<o{idx}> = {want}")
        else:
            raise ValueError(f"pred {pn}")


def enc2_rels() -> str:
    out = [";; ---------- enc2: form x alternative -> clause ----------",
           "enc2 : <op, labs, pc4> <-> <bytes> where {"]
    for form, alts in isa.ENCS.items():
        _, op, w, ext, _ = isa.FORMS[form]
        arity = _operand_arity(form)
        pat = ("'op('" + form +
               (", " + ", ".join(f"o{i}" for i in range(arity))
                if arity else "") + ")")
        earlier = []
        for conds, tmpl in alts:
            g = Gen()
            goals = [f"      op = {pat}"]
            _pred_goals(conds, False, g, goals)
            for c in earlier:
                _pred_goals([c], True, g, goals)
            needs_pcva = any(f[0] == "rel" for f in tmpl)
            pcva = None
            if needs_pcva:
                pcva = g.v()
                goals.insert(1, "      bs4_add<" + bs4(TRVA) +
                             f", pc4, 0> = {pcva}")
            acc = "[]"
            dispvar = None
            for f in tmpl:
                nv = g.v()
                if f[0] == "raw":
                    goals.append(f"      {nv} = {bl(f[1:])}")
                elif f[0] == "op":
                    v = f[1] if len(f) > 1 else op
                    goals.append(f"      {nv} = {bl(opbytes(v))}")
                elif f[0] == "oprd":
                    lo = g.v()
                    goals.append(
                        f"      regc<o0> = PAIR({lo}, _)")
                    b = g.v()
                    goals.append(
                        f"      bplus<ATOM(8,{op}), {lo}> = {b}")
                    goals.append(f"      {nv} = [{b}]")
                elif f[0] == "rex":
                    call, nv = _rex_call(f[1:], w, g)
                    goals.append(call)
                elif f[0] == "modrm":
                    reg, rm = f[1], f[2]
                    if isinstance(reg, int):
                        rf = f"ATOM(8,{reg << 3})"
                    elif reg == "ext":
                        rf = f"ATOM(8,{ext << 3})"
                    else:
                        rf = g.v()
                        goals.append(f"      rfx<o{reg[3:]}> = {rf}")
                    if rm == "rip":
                        b = g.v()
                        goals.append(f"      mrm_rip<{rf}> = {b}")
                        goals.append(f"      {nv} = [{b}]")
                    elif rm.startswith("rm"):
                        lo8 = g.v()
                        b = g.v()
                        goals.append(
                            f"      plo8<o{rm[2:]}> = {lo8}")
                        goals.append(
                            f"      mrm_rr<{rf}, {lo8}> = {b}")
                        goals.append(f"      {nv} = [{b}]")
                    else:  # memI
                        bv, dv = g.v(), g.v()
                        dlv = g.v()
                        goals.append(
                            f"      o{rm[3:]} = 'm({bv}, {dv})")
                        goals.append(
                            f"      mem_f<{rf}, {bv}, {dv}> = "
                            f"PAIR({nv}, {dlv})")
                        dispvar = dlv
                elif f[0] == "disp":
                    nv = dispvar
                elif f[0] == "imm":
                    nlv = g.v()
                    goals.append(f"      o{f[2]} = 'i({nlv})")
                    fn = {"i8": "im8", "i32": "im32",
                          "i64": "im64"}[f[1]]
                    goals.append(f"      {fn}<{nlv}> = {nv}")
                elif f[0] == "rel":
                    goals.append(
                        f"      relfix<o{f[1]}, labs, {acc}, "
                        f"{pcva}> = {nv}")
                else:
                    raise ValueError(f)
                av = g.v()
                goals.append(f"      append<{acc}, {nv}> = {av}")
                acc = av
            goals.append(f"      bytes = {acc}")
            ovars = ", ".join(f"o{i}" for i in range(arity))
            fvars = ", ".join(f"v{i}" for i in range(1, g.n + 1))
            decls = ", ".join(x for x in (ovars, fvars) if x)
            out.append(f"  | fresh({decls}) {{")
            out.extend(goals)
            out.append("    }")
            earlier.extend(conds)
    out.append("}")
    return "\n".join(out)


def enc2_len_rels() -> str:
    """Length-only mirror of enc2: same alt selection, byte counts
    instead of bytes.  rel fields are always 4; mem disp/rex widths
    discriminate on the same data as enc2."""
    out = [";; ---------- enc2_len: same selection, lengths ----------",
           "enc2_len : <op> <-> <n4> where {"]
    for form, alts in isa.ENCS.items():
        _, op, w, ext, _ = isa.FORMS[form]
        arity = _operand_arity(form)
        pat = ("'op('" + form +
               (", " + ", ".join(f"o{i}" for i in range(arity))
                if arity else "") + ")")
        earlier = []
        for conds, tmpl in alts:
            # mem operand positions needing disp-case splits â€”
            # the same exclusive 7-way partition as mem_f:
            # k0 nlz lo!45 ->1; k1 nlz lo4 ->2; k2 nlz lo5 ->2;
            # k3 nz&se8 lo!4 ->2; k4 nz&se8 lo4 ->3;
            # k5 nz&!se8 lo!4 ->5; k6 nz&!se8 lo4 ->6
            memis = [f[2] for f in tmpl
                     if f[0] == "modrm" and str(f[2]).startswith("mem")]
            cases = [(None, 0)] if not memis else \
                [(m, k) for m in memis for k in range(7)]
            for memi, k in cases:
                g = Gen()
                goals = [f"      op = {pat}"]
                _pred_goals(conds, False, g, goals)
                for c in earlier:
                    _pred_goals([c], True, g, goals)
                acc = bs4(0)
                dispvar = None
                for f in tmpl:
                    if f[0] == "raw":
                        add = len(f[1:])
                    elif f[0] == "op":
                        v = f[1] if len(f) > 1 else op
                        add = len(opbytes(v))
                    elif f[0] == "oprd":
                        add = 1
                    elif f[0] == "rex":
                        # data-dependent â€” measure actual emission
                        call, nv = _rex_call(f[1:], w, g)
                        goals.append(call)
                        lv = g.v()
                        goals.append(f"      len4<{nv}> = {lv}")
                        av = g.v()
                        goals.append(
                            f"      bs4_add<{acc}, {lv}, "
                            f"0> = {av}")
                        acc = av
                        continue
                    elif f[0] == "modrm":
                        rm = f[2]
                        if rm.startswith("mem"):
                            # case k: 0=disp0 lo!=4,5; 1=disp0 lo4;
                            # 2=se8; 3=se8 lo4; 4=disp32; 5=disp32 lo4
                            bv, dv = g.v(), g.v()
                            lov = g.v()
                            goals.append(
                                f"      o{rm[3:]} = 'm({bv}, {dv})")
                            goals.append(
                                f"      regc<{bv}> = "
                                f"PAIR({lov}, _)")
                            if k == 0:
                                goals.append(f"      nlz<{dv}> = _")
                                goals.append(
                                    f"      {lov} != ATOM(4,4)")
                                goals.append(
                                    f"      {lov} != ATOM(4,5)")
                                add = 1
                            elif k == 1:
                                goals.append(f"      nlz<{dv}> = _")
                                goals.append(
                                    f"      {lov} = ATOM(4,4)")
                                add = 2
                            elif k == 2:
                                goals.append(f"      nlz<{dv}> = _")
                                goals.append(
                                    f"      {lov} = ATOM(4,5)")
                                add = 2
                            elif k in (3, 4):
                                goals.append(
                                    f"      nlzf<{dv}> = 0")
                                goals.append(
                                    f"      se8f<{dv}> = 1")
                                goals.append(
                                    f"      {lov} "
                                    + ("!= " if k == 3 else "= ")
                                    + "ATOM(4,4)")
                                add = 2 if k == 3 else 3
                            else:
                                goals.append(
                                    f"      nlzf<{dv}> = 0")
                                goals.append(
                                    f"      se8f<{dv}> = 0")
                                goals.append(
                                    f"      {lov} "
                                    + ("!= " if k == 5 else "= ")
                                    + "ATOM(4,4)")
                                add = 5 if k == 5 else 6
                            dispvar = 0  # consumed by "disp" field
                        elif rm == "rip" or rm.startswith("rm"):
                            add = 1
                    elif f[0] == "disp":
                        add = 0
                    elif f[0] == "imm":
                        add = {"i8": 1, "i32": 4, "i64": 8}[f[1]]
                    elif f[0] == "rel":
                        add = 4
                    else:
                        raise ValueError(f)
                    if add:
                        av = g.v()
                        goals.append(
                            f"      bs4_add<{acc}, {bs4(add)}, "
                            f"0> = {av}")
                        acc = av
                goals.append(f"      n4 = {acc}")
                ovars = ", ".join(f"o{i}" for i in range(arity))
                fvars = ", ".join(f"v{i}" for i in range(1, g.n + 1))
                decls = ", ".join(x for x in (ovars, fvars) if x)
                out.append(f"  | fresh({decls}) {{")
                out.extend(goals)
                out.append("    }")
            earlier.extend(conds)
    out.append("}")
    return "\n".join(out)


ASSEMBLER = """
;; ---------- assembler ----------

;; pass1: label -> section-offset rows (bs4); insns advance pc by
;; enc2_len — label-independent by construction.
pass1 : <ops, pc4> <-> <labs> shape self where {
  | ops = [] { labs = [] }
  | fresh(o, n, rest, lb) {
      ops = PAIR(o, rest)   o = 'label(n)
      pass1<rest, pc4> = lb
      labs = PAIR(PAIR(n, pc4), lb)
    }
  | fresh(o, rest, n4, pc2, lb) {
      ops = PAIR(o, rest)   o = PAIR('op, _)
      enc2_len<o> = n4
      bs4_add<pc4, n4, 0> = pc2
      pass1<rest, pc2> = lb
      labs = lb
    }
}

assemble2 : <ops, labs, pc4> <-> <bytes> shape self where {
  | ops = [] { bytes = [] }
  | fresh(o, rest, rb) {
      ops = PAIR(o, rest)   o = 'label(_)
      assemble2<rest, labs, pc4> = rb
      bytes = rb
    }
  | fresh(o, rest, eb, n4, pc2, rb) {
      ops = PAIR(o, rest)   o = PAIR('op, _)
      enc2<o, labs, pc4> = eb
      enc2_len<o> = n4
      bs4_add<pc4, n4, 0> = pc2
      assemble2<rest, labs, pc2> = rb
      append<eb, rb> = bytes
    }
}

assemble : <ops> <-> <bytes> where {
  | fresh(labs) {
      pass1<ops, %s> = labs
      assemble2<ops, labs, %s> = bytes
    }
}
""" % (bs4(0), bs4(0))


def render() -> str:
    nib = "\n".join(
        f"  | n = ATOM(4,{n})  {{ p = ATOM(4,{(n - 1) & 15})   "
        f"w = ATOM(4,{1 if n == 0 else 0}) }}" for n in range(16))
    shl = "\n".join(f"  | h = ATOM(4,{h})  {{ v = {h * 16} }}"
                    for h in range(16))
    lon = "\n".join(f"  | n = ATOM(4,{n}) {{ ok = 1 }}"
                    for n in range(8))
    hin = "\n".join(f"  | n = ATOM(4,{n}) {{ ok = 1 }}"
                    for n in range(8, 16))
    lonf = "\n".join(f"  | n = ATOM(4,{n}) {{ f = {1 if n < 8 else 0} }}"
                     for n in range(16))
    hinf = "\n".join(f"  | n = ATOM(4,{n}) {{ f = {1 if n >= 8 else 0} }}"
                     for n in range(16))
    c48 = "\n".join(f"  | n = ATOM(4,{n}) {{ b = {n} }}"
                    for n in range(8))
    rflo = "\n".join(
        f"  | rf = ATOM(8,{r}) & lo = ATOM(8,{l}) {{ s = {r + l} }}"
        for r in range(0, 64, 8) for l in range(8))
    body = (NIBBLE
            .replace("%%NIBBLE_PRED%%", nib)
            .replace("%%SHL4%%", shl)
            .replace("%%LON4%%", lon)
            .replace("%%HIN4%%", hin)
            .replace("%%LON4F%%", lonf)
            .replace("%%HIN4F%%", hinf))
    regs = reg_tables().replace("%%C48%%", c48)
    fields = (FIELD_RELS
              .replace("%%RFLO%%", rflo)
              .replace("%%TRVA4%%", bs4(TRVA))
              .replace("%%FOUR4%%", bs4(4)))
    return (HEADER + body + "\n" + regs + "\n" + fields + "\n"
            + symtab_rel() + "\n\n" + rex_rels() + "\n"
            + enc2_rels() + "\n\n" + enc2_len_rels() + "\n"
            + ASSEMBLER)


if __name__ == "__main__":
    sys.stdout.write(render())
