"""gen_x86_map â€” synthesize the x86-64 win64 assembly map (.phi)
from the mined ISA row data.

The translator treats host/isa_x86_64.py's ENCS/INSN/REG tables as
the source of truth:

  - each ENCS alternative          -> one enc2 clause
  - each field op                  -> a call into shared field rels
  - each predicate                 -> a flag rel (0/1), and later
    alternatives carry earlier preds' negations â€” ordered
    alternatives stay exclusive without negation-as-failure
  - enc2_len mirrors enc2          -> pass1's label->offset rows;
    widths are label-independent (rel is always 4 bytes, imm/disp
    widths depend only on operand values)

Numbers are corpus-native: immediates ('i(nl)), mem disps, pcs and
symtab values are LE nibble lists; fixups compute
disp = target_rva - (trva + pc + len) through nibble_add/nibble_sub
â€” two's-complement wrap by construction.

Src operand terms:
  reg name   -> bare sym ('rax, 'ecx, 'al)
  imm        -> 'i(nl)        canonical nl8 (|v| < 2^31) or nl16
  mem        -> 'm(base, nl8) ('m', basereg, disp)
  rip-rel    -> 'p(name)      symtab-resolved target
  rel32      -> 'l(name)      label-resolved target
  label item -> 'label(name)

Usage:  python host/gen_x86_map.py > phi2/maps/assemble_x86_win64.phi
"""
