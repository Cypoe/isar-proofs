#!/usr/bin/env python3
"""host2.check — the C witness gate.

host2's witness is `src/krun.c` — a C99 Role-B checker for the
`[flow-eval]` claim wire (the same format FlowCheck.lean decides and
golden.txt lists). This script only orchestrates it; it contains no
evaluator logic of its own:

  build : clang -std=c99 -Wall -Wextra -Werror src/krun.c -> krun
  claim : krun case-N.k -> exit 0 / "ok ..."        (re-decide + agree)
          krun case-forged.k -> exit 4 / "drift"     (forged rejected)
          krun kemit.k -> "ok refuse"                (arg-less emit)
  emit  : krun kemit.k --emit case-N.k -> the claim's `# emit:` text
  cc    : emitted C -> clang -> run -> exit code == literal

Corpus files are GENERATED by tools/DumpKoruFixtures.lean — the
`# emit:` comment carries the emitC99 expectation, `refuse` means the
program is outside the realized subset.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys

_HOST2 = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HOST2)
SRC = os.path.join(_HOST2, "src", "krun.c")
KRUN = os.path.join(_HOST2, "build", "krun.exe" if os.name == "nt" else "krun")
CORPUS = os.path.join(_HOST2, "specs", "corpus")
BUILD = os.path.join(_HOST2, "build")

CLANG = r"C:\Program Files\clang+llvm-18.1.8-x86_64-pc-windows-msvc\bin\clang"


def _clang():
    if os.path.exists(CLANG):
        return CLANG
    return shutil.which("clang")


def _emit_want(path):
    """The `# emit:` header line — C text or `refuse`."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"# emit: (.*)$", line.rstrip("\n"))
            if m:
                return m.group(1).strip()
            if not line.startswith("#"):
                break
    return None


def gate():
    npass = nfail = nskip = 0

    def ok(name, detail=""):
        nonlocal npass
        npass += 1
        print(f"  pass  {name}" + (f"  ({detail})" if detail else ""))

    def bad(name, detail):
        nonlocal nfail
        nfail += 1
        print(f"  FAIL  {name}  ({detail})")

    def skip(name, detail):
        nonlocal nskip
        nskip += 1
        print(f"  skip  {name}  ({detail})")

    # ---- build leg: the witness must compile clean ----
    cc = _clang()
    if cc is None:
        bad("build", "no clang found")
        print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
        return 1
    os.makedirs(BUILD, exist_ok=True)
    c = subprocess.run(
        [cc, "-std=c99", "-Wall", "-Wextra", "-Werror", "-O1",
         SRC, "-o", KRUN],
        capture_output=True, text=True)
    if c.returncode != 0:
        bad("build", c.stderr.strip()[:300])
        print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
        return 1
    ok("build", "clang -std=c99 -Werror")
    krun = KRUN

    # ---- claim legs: every corpus row re-decided by C ----
    cases = sorted(
        f for f in os.listdir(CORPUS)
        if re.match(r"case-\d+\.k$", f))
    for fname in cases:
        cid = fname[:-2]
        r = subprocess.run([krun, os.path.join(CORPUS, fname)],
                           capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.startswith("ok "):
            ok(f"{cid}.claim", r.stdout.strip())
        else:
            bad(f"{cid}.claim",
                f"exit={r.returncode} out={r.stdout.strip()[:120]} "
                f"err={r.stderr.strip()[:120]}")

    r = subprocess.run([krun, os.path.join(CORPUS, "case-forged.k")],
                       capture_output=True, text=True)
    if r.returncode == 4 and r.stderr.startswith("drift:"):
        ok("forged.claim", "forged claim rejected with drift")
    else:
        bad("forged.claim",
            f"exit={r.returncode} out={r.stdout.strip()[:120]}")

    r = subprocess.run([krun, os.path.join(CORPUS, "kemit.k")],
                       capture_output=True, text=True)
    if r.returncode == 0 and "refuse" in r.stdout:
        ok("kemit.argless", "missing src refuses")
    else:
        bad("kemit.argless",
            f"exit={r.returncode} out={r.stdout.strip()[:120]}")

    # ---- emit legs: kemit.k as data, src = quoted claim program ----
    kemit = os.path.join(CORPUS, "kemit.k")
    for fname in cases:
        cid = fname[:-2]
        path = os.path.join(CORPUS, fname)
        want = _emit_want(path)
        r = subprocess.run([krun, kemit, "--emit", path],
                           capture_output=True, text=True)
        if want == "refuse":
            if r.returncode == 3:
                ok(f"{cid}.emit", "outside subset refuses")
            else:
                bad(f"{cid}.emit",
                    f"expected refusal, exit={r.returncode} "
                    f"out={r.stdout.strip()[:120]}")
            continue
        if r.returncode == 0 and r.stdout.strip() == want:
            ok(f"{cid}.emit", want[:60])
        else:
            bad(f"{cid}.emit",
                f"exit={r.returncode} got={r.stdout.strip()[:80]!r} "
                f"want={want[:80]!r}")
            continue

        # ---- cc leg: compile the emitted C, run it, compare exit ----
        m = re.search(r"return (-?\d+)", want)
        if not m:
            skip(f"{cid}.cc", "no return literal in emit text")
            continue
        expect = int(m.group(1)) & 0xFFFFFFFF
        csrc = os.path.join(BUILD, f"{cid}.emit.c")
        cexe = os.path.join(BUILD, f"{cid}.emit.exe")
        with open(csrc, "w", encoding="utf-8") as f:
            f.write(r.stdout)
        c = subprocess.run([cc, "-std=c99", "-O0", csrc, "-o", cexe],
                           capture_output=True, text=True)
        if c.returncode != 0:
            bad(f"{cid}.cc", f"clang refused: {c.stderr.strip()[:160]}")
            continue
        run = subprocess.run([cexe], capture_output=True)
        got = run.returncode & 0xFFFFFFFF
        if got == expect:
            ok(f"{cid}.cc", f"exit {got}")
        else:
            bad(f"{cid}.cc", f"exit {got} != {expect}")

    print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
    return 0 if nfail == 0 else 1


if __name__ == "__main__":
    raise SystemExit(gate())
