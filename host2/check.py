#!/usr/bin/env python3
"""host2.check — the C witness gate.

host2's witnesses are two C99 tools over the declared rows in
`specs/`:

  korufe : .k (real koru surface) -> program.ast.json (canon shape)
           --lower -> [flow-eval] claim (the lower-layer wire)
  krun   : the [flow-eval] claim checker / evaluator / emitter host

The pipeline per case row in `specs/cases.json`:

  parse : korufe FILE.k -> build/KEY.ast.json
  lower : korufe --lower ast cases.json KEY -> build/KEY.claim
  claim : krun claim -> "ok ..." | forged -> "drift" exit 4
  emit  : krun kemit.claim --emit claim -> row's expected emit text
          ("refuse" for out-of-subset rows)
  cc    : emitted .c compiled by the assembly.json c99 toolchain row,
          run -> exit DWORD == the literal

Spec rows consumed as data: cases.json (entry/fuel/expect/emit/oracle),
assembly.json (cc + flags + run semantics). Refusal probes assert the
frontend's refuse-by-default contract. This script is orchestration
only — no evaluator, parser, or emission logic lives here.

Corpus .k files + cases.json are GENERATED by
tools/DumpKoruFixtures.lean — real koru syntax, never edited.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

_HOST2 = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HOST2)
SRC_KRUN = os.path.join(_HOST2, "src", "krun.c")
SRC_KORUFE = os.path.join(_HOST2, "src", "korufe.c")
KRUN = os.path.join(_HOST2, "build", "krun.exe" if os.name == "nt" else "krun")
KORUFE = os.path.join(_HOST2, "build", "korufe.exe" if os.name == "nt" else "korufe")
CORPUS = os.path.join(_HOST2, "specs", "corpus")
SPECS = os.path.join(_HOST2, "specs")
BUILD = os.path.join(_HOST2, "build")

CLANG = r"C:\Program Files\clang+llvm-18.1.8-x86_64-pc-windows-msvc\bin\clang"


def _clang():
    if os.path.exists(CLANG):
        return CLANG
    return shutil.which("clang")


def _load(spec):
    with open(os.path.join(SPECS, spec), encoding="utf-8") as f:
        return json.load(f)


def _c99_row():
    for t in _load("assembly.json")["targets"]:
        if t["id"] == "c99":
            return t
    return None


def gate():
    npass = nfail = nskip = 0

    def ok(name, detail=""):
        nonlocal npass
        npass += 1
        print(f"  pass  {name}" + (f"  ({detail})" if detail else ""))

    def bad(name, detail):
        nonlocal nfail
        nfail += 1
        print(f"  FAIL  {name}  ({detail})")

    def skip(name, detail):
        nonlocal nskip
        nskip += 1
        print(f"  skip  {name}  ({detail})")

    cc = _clang()
    if cc is None:
        bad("build", "no clang found")
        print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
        return 1
    os.makedirs(BUILD, exist_ok=True)

    cases = _load("cases.json")["cases"]
    target = _c99_row()
    if target is None:
        bad("specs", "assembly.json has no c99 target row")
        return 1
    tc = target["toolchain"]

    # ---- build legs: both witnesses compile clean ----
    built = True
    for tag, src, out in (("krun", SRC_KRUN, KRUN),
                          ("korufe", SRC_KORUFE, KORUFE)):
        c = subprocess.run(
            [cc, "-std=c99", "-Wall", "-Wextra", "-Werror", "-O1",
             src, "-o", out],
            capture_output=True, text=True)
        if c.returncode != 0:
            bad(f"build.{tag}", c.stderr.strip()[:300])
            built = False
        else:
            ok(f"build.{tag}", "clang -std=c99 -Werror")
    if not built:
        print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
        return 1

    # ---- per-case legs: parse -> lower -> claim -> emit -> cc ----
    kemit_claim = None
    for key in sorted(cases):
        row = cases[key]
        src = os.path.join(CORPUS, row["file"])
        ast = os.path.join(BUILD, f"{key}.ast.json")
        claim = os.path.join(BUILD, f"{key}.claim")

        r = subprocess.run([KORUFE, src], capture_output=True, text=True)
        if r.returncode == 0:
            with open(ast, "w", encoding="utf-8") as f:
                f.write(r.stdout)
            ok(f"{key}.parse", "ast.json")
        else:
            bad(f"{key}.parse", r.stderr.strip()[:160])
            continue

        r = subprocess.run([KORUFE, "--lower", ast,
                            os.path.join(SPECS, "cases.json"), key],
                           capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.startswith("[flow-eval]"):
            with open(claim, "w", encoding="utf-8") as f:
                f.write(r.stdout)
            ok(f"{key}.lower", "claim")
        else:
            bad(f"{key}.lower",
                f"exit={r.returncode} {r.stderr.strip()[:160]}")
            continue

        forged = row.get("forged")
        r = subprocess.run([KRUN, claim], capture_output=True, text=True)
        if forged:
            if r.returncode == 4 and r.stderr.startswith("drift:"):
                ok(f"{key}.claim", "forged rejected with drift")
            else:
                bad(f"{key}.claim",
                    f"forged not caught: exit={r.returncode} "
                    f"{r.stdout.strip()[:120]}")
        else:
            if r.returncode == 0 and r.stdout.startswith("ok "):
                ok(f"{key}.claim", r.stdout.strip()[:80])
            else:
                bad(f"{key}.claim",
                    f"exit={r.returncode} out={r.stdout.strip()[:120]} "
                    f"err={r.stderr.strip()[:120]}")

        if key == "kemit":
            kemit_claim = claim

    # ---- emit legs: kemit's claim + --emit against every case claim ----
    if kemit_claim is None:
        bad("emit", "kemit claim not built")
    else:
        for key in sorted(cases):
            row = cases[key]
            if row.get("emit_prog") or row.get("forged"):
                continue
            claim = os.path.join(BUILD, f"{key}.claim")
            if not os.path.exists(claim):
                continue
            want = row["emit"]
            r = subprocess.run([KRUN, kemit_claim, "--emit", claim],
                               capture_output=True, text=True)
            if want == "refuse":
                if r.returncode == 3:
                    ok(f"{key}.emit", "outside subset refuses")
                else:
                    bad(f"{key}.emit",
                        f"expected refusal, exit={r.returncode} "
                        f"out={r.stdout.strip()[:120]}")
                continue
            if r.returncode == 0 and r.stdout.strip() == want:
                ok(f"{key}.emit", want[:60])
            else:
                bad(f"{key}.emit",
                    f"exit={r.returncode} got={r.stdout.strip()[:80]!r} "
                    f"want={want[:80]!r}")
                continue

            # ---- cc leg: assembly.json toolchain, run, exit DWORD ----
            m = re.search(r"return (-?\d+)", want)
            if not m:
                skip(f"{key}.cc", "no return literal in emit text")
                continue
            expect = int(m.group(1)) & 0xFFFFFFFF
            csrc = os.path.join(BUILD, f"{key}.emit.c")
            cexe = os.path.join(BUILD, f"{key}.emit.exe")
            with open(csrc, "w", encoding="utf-8") as f:
                f.write(r.stdout)
            c = subprocess.run([tc["cc"], *tc["flags"], csrc, "-o", cexe],
                               capture_output=True, text=True)
            if c.returncode != 0:
                bad(f"{key}.cc", f"{tc['cc']} refused: {c.stderr.strip()[:160]}")
                continue
            run = subprocess.run([cexe], capture_output=True)
            got = run.returncode & 0xFFFFFFFF
            if got == expect:
                ok(f"{key}.cc", f"exit {got}")
            else:
                bad(f"{key}.cc", f"exit {got} != {expect}")

    # ---- refusal probes: the frontend refuses by default ----
    probes = [
        ("malformed", "tor main {\n", "unterminated decl refuses"),
        ("unknown-item", "frobulate x\n", "unknown item refuses"),
        ("impl-ctor", "tor s {}\n| go\ns => go\n",
         "name => b impl refuses (subset axis)"),
        ("no-such-case", None, "missing case row refuses"),
    ]
    for tag, text, desc in probes:
        if text is None:
            r = subprocess.run(
                [KORUFE, "--lower",
                 os.path.join(BUILD, "case-0.ast.json"),
                 os.path.join(SPECS, "cases.json"), "nope"],
                capture_output=True, text=True)
        else:
            with tempfile.NamedTemporaryFile(
                    "w", suffix=".k", delete=False) as f:
                f.write(text)
                tmp = f.name
            r = subprocess.run([KORUFE, tmp], capture_output=True, text=True)
            os.unlink(tmp)
        if r.returncode == 2 and "refuse" in r.stderr:
            ok(f"refuse.{tag}", desc)
        else:
            bad(f"refuse.{tag}",
                f"exit={r.returncode} out={r.stdout.strip()[:100]} "
                f"err={r.stderr.strip()[:100]}")

    print(f"host2.check: {npass} pass, {nfail} fail, {nskip} skip")
    return 0 if nfail == 0 else 1


if __name__ == "__main__":
    raise SystemExit(gate())
