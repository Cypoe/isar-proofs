#!/usr/bin/env python3
"""host2.fixtures — the witness gate.

For every case in specs/koru-fixtures.json (GENERATED by
tools/DumpKoruFixtures.lean — never hand-edit), host2 must reproduce
what the Lean dialect decided, independently:

  quote : quote.quote_prog(prog) == quoted_src
  eval  : run.eval_prog(prog, fuel)  == eval
  kemit : run.eval_prog on kEmit with ("src", our_quote(prog)) == kemit
          and its str payload == emit (the emitC99 text)

plus the cc leg: emitted C is compiled (clang; falls back to `zig cc`,
skips if neither exists) and the binary's exit code must equal the
literal it returns — the end-to-end run witness.

Every check is named; a failure prints both sides.  Refusals are
first-class rows (expect == null must produce None).
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys

_HOST2 = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HOST2)
for _p in (_HOST2, os.path.join(_ROOT, "host")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import kwire   # noqa: E402
import quote   # noqa: E402
import run     # noqa: E402

FIXTURES = os.path.join(_HOST2, "specs", "koru-fixtures.json")
BUILD = os.path.join(_ROOT, "_scratch", "host2")


def _cc():
    for cand in ("clang", "zig"):
        path = shutil.which(cand)
        if path:
            return (path, cand == "zig")
    return (None, False)


def _cc_leg(c_text, expect_int):
    """Compile the emitted C, run it, compare the exit code."""
    cc, is_zig = _cc()
    if cc is None:
        return ("skip", "no clang/zig on PATH")
    os.makedirs(BUILD, exist_ok=True)
    src = os.path.join(BUILD, "emit_probe.c")
    exe = os.path.join(BUILD, "emit_probe.exe")
    with open(src, "w", encoding="utf-8") as f:
        f.write(c_text + "\n")
    cmd = [cc, "-O0", "-x", "c", src, "-o", exe]
    if is_zig:
        cmd = [cc, "cc", "-O0", src, "-o", exe]
    c = subprocess.run(cmd, capture_output=True, text=True)
    if c.returncode != 0:
        return ("fail", f"cc refused: {c.stderr.strip()[:200]}")
    r = subprocess.run([exe], capture_output=True)
    want = expect_int & 0xFFFFFFFF
    got = r.returncode & 0xFFFFFFFF
    if got != want:
        return ("fail", f"exit {got} != {want}")
    return ("pass", f"exit {got} == {want} ({os.path.basename(cc)})")


def _subset_int(prog):
    """The literal the subset's single main returns (emit!=null only)."""
    try:
        return prog["graph"][0][1]["bare"]["lit"]["int"]
    except (KeyError, IndexError, TypeError):
        return None


def gate():
    doc = json.load(open(FIXTURES, encoding="utf-8"))
    fuel = doc["fuel"]
    kemit = doc["programs"]["kemit"]
    kwire.validate_prog(kemit, "programs.kemit")

    npass = nfail = nskip = 0

    def check(cid, name, got, want):
        nonlocal npass, nfail
        if got == want:
            npass += 1
            print(f"  pass  {cid:<10} {name}")
        else:
            nfail += 1
            print(f"  FAIL  {cid:<10} {name}")
            print(f"        got : {json.dumps(got)[:180]}")
            print(f"        want: {json.dumps(want)[:180]}")

    for case in doc["cases"]:
        cid = f"case-{case['id']}"
        prog = case["prog"]
        kwire.validate_prog(prog, f"{cid}.prog")
        kwire.validate_val(case["quoted_src"], f"{cid}.quoted_src")

        # quote witness — our quotation must match Lean's quoteProg.
        ours_q = quote.quote_prog(prog)
        check(cid, "quote", ours_q, case["quoted_src"])

        # eval witness — our runK must match evalKProg's decision.
        check(cid, "eval", run.eval_prog(prog, [], fuel), case["eval"])

        # the fixpoint row — OUR quote feeding kEmit under OUR runK
        # must match runK(kEmit) under Lean.
        ours = run.as_kresult(
            run.run_k(kemit["graph"], [], fuel,
                      ("invoke", "emit", [["src", ours_q]]))
        )
        check(cid, "kemit", ours, case["kemit"])

        # cross-consistency: accepted rows' str payload is the C text.
        if case["emit"] is not None:
            want = {"branch": None, "payload": {"str": case["emit"]}}
            check(cid, "emit==kemit.payload", ours, want)
            outcome, detail = _cc_leg(case["emit"], _subset_int(prog))
            if outcome == "skip":
                nskip += 1
                print(f"  skip  {cid:<10} cc ({detail})")
            elif outcome == "pass":
                npass += 1
                print(f"  pass  {cid:<10} cc ({detail})")
            else:
                nfail += 1
                print(f"  FAIL  {cid:<10} cc ({detail})")

    print(f"host2.fixtures: {npass} pass, {nfail} fail, {nskip} skip")
    return 0 if nfail == 0 else 1


if __name__ == "__main__":
    raise SystemExit(gate())
